const assert = require('node:assert/strict');
const fs = require('node:fs'); const ts = require('typescript');
const out = ts.transpileModule(fs.readFileSync(require('node:path').resolve(__dirname, '../lib/sms.ts'), 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText;
const m = {exports: {}}; new Function('module', 'exports', out)(m, m.exports);
const {normalizePhone, buildOnwayText, buildCourierText} = m.exports;
assert.equal(normalizePhone('555 55 55 55'), '995555555555');
assert.equal(normalizePhone('+995 514 351 331'), '995514351331');
assert.equal(normalizePhone('322123456'), null);
const V = '10% ვაუჩერი გაგიაქტიურდათ.';
assert.equal(buildCourierText({paymentType:'prepaid', total:100}), V + 'შეკვეთა გზაშია,ყურადღებით იყავით ტელეფონთან');
assert.equal(buildCourierText({paymentType:'cod', total:35}), V + 'შეკვეთა გზაშია,კურიერთან გადაიხდით 35ლარს');
assert.equal(buildOnwayText({tracking:'T1', paymentType:'cod', total:40, city:'ბათუმი'}), V + 'შეკვეთა T1 გზაშია, კურიერთან 40 ლარი');
assert.equal(buildOnwayText({tracking:'T1', paymentType:'prepaid', total:40, city:'თბილისი'}), V + 'შეკვეთა T1 გზაშია,მიწოდების ვადა 2დღე');
assert.equal(buildOnwayText({tracking:'T1', paymentType:'prepaid', total:40, city:'ქუთაისი'}), V + 'შეკვეთა T1 გზაშია,მიწოდების ვადა 4დღე');
